"""Generate each use skill's "Builds on" block from the dependency graph.

A repository's plugin (``plugins/<name>/`` in its submodule) ships its use
skills. The skill tree links them along the dependency graph: at the end of
each ``SKILL.md`` a "Builds on" block carries one contract card per
repository the skill's repository depends on, and a "Used by" line.

The graph is ``dependency_graph.py``'s, so nobody writes an edge by hand. A
repository whose plugin ships a shelf (``plugins/<name>/tree/shelf.toml``)
is carded by unit: a dependent's block carries only the cards of the units
``skill_shelf.py`` measures it using.

A card is read from the first of these that exists:

- ``plugins/<name>/tree/cards/<unit>.md`` in the repository, for a unit;
- ``plugins/<name>/tree/card.md`` in the repository;
- ``skill_tree/cards/<repository>.md`` here, for a repository that does not
  ship its own card yet, or that is third party.

It also writes ``.claude-plugin/marketplace.json``, which lists geostack's
root plugin (the ``role-ladder`` skill) and every repository's plugin, each
with the plugins it depends on, so that installing one installs the skills
below it.

geostack never commits into a submodule. ``--write`` puts a repository's
blocks into a checkout of it, for a pull request there, like
``dependency_graph.py --guard``.

    python scripts/skill_tree.py                       # the marketplace; print the tree
    python scripts/skill_tree.py --check               # exit 1 if a gate fails
    python scripts/skill_tree.py --write kernellib     # into its submodule
    python scripts/skill_tree.py --write gaussx --into ../gaussx
"""

from __future__ import annotations

import argparse
import ast
import configparser
import graphlib
import json
import re
import sys
import tomllib
from dataclasses import dataclass, field
from pathlib import Path


sys.path.insert(0, str(Path(__file__).resolve().parent))
import dependency_graph as dg
import skill_shelf as ss


ROOT = Path(__file__).resolve().parents[1]
#: cards geostack holds for a repository that ships none of its own
CARDS = ROOT / "skill_tree" / "cards"

#: the marketplace that installs a skill together with the skills it builds on
MARKETPLACE = ROOT / ".claude-plugin" / "marketplace.json"
#: geostack's own plugin, the root of the tree: it holds the role-ladder skill
ROOT_PLUGIN = "geostack"

BLOCK_BEGIN = (
    "<!-- skill-tree:begin · generated by geostack scripts/skill_tree.py;"
    " do not edit by hand -->"
)
BLOCK_MARK = "<!-- skill-tree:begin"
BLOCK_END = "<!-- skill-tree:end -->"

#: Claude Code's recommendation for a SKILL.md and its cap on a description
SKILL_MAX_LINES = 500
DESCRIPTION_MAX_CHARS = 1536
#: a card is read on every load of every dependent's skill
CARD_MAX_LINES = 15

EDGE_KINDS = {
    "base": "base dependency",
    "extra": "extra",
    "import": "guarded import",
}


@dataclass(frozen=True)
class Unit:
    """A unit of a shelf: the listed skill it sits in and its card."""

    key: str
    title: str
    rungs: str
    skill: str


@dataclass(frozen=True)
class Node:
    """One repository: where its plugin is and what the plugin ships."""

    repo: str
    path: Path  # the checkout its plugin is read from
    plugin: str | None  # the plugin's directory name under plugins/
    skills: tuple[str, ...]  # listed skills; the first is the front door
    units: dict[str, Unit] = field(default_factory=dict)  # empty without a shelf

    @property
    def plugin_dir(self) -> Path:
        return self.path / "plugins" / str(self.plugin)

    def skill_file(self, skill: str) -> Path:
        return self.plugin_dir / "skills" / skill / "SKILL.md"


@dataclass(frozen=True)
class Edge:
    """A dependency of a repository, with the parent's units it uses."""

    parent: str
    kind: str
    units: tuple[str, ...] = ()


@dataclass
class Tree:
    """Every repository of the stack and what each builds on, bottom-up."""

    nodes: dict[str, Node]
    edges: dict[str, tuple[Edge, ...]]

    def children(self, repo: str) -> list[str]:
        """Repositories that depend directly on ``repo``."""
        return sorted(
            r for r, es in self.edges.items() if any(e.parent == repo for e in es)
        )

    def below(self, repo: str) -> set[str]:
        """Every repository ``repo`` depends on, directly or through another."""
        found: set[str] = set()
        stack = [e.parent for e in self.edges.get(repo, ())]
        while stack:
            r = stack.pop()
            if r not in found:
                found.add(r)
                stack.extend(e.parent for e in self.edges.get(r, ()))
        return found


def slug(title: str) -> str:
    """A unit's key from its title: ``State space`` gives ``state-space``."""
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")


def read_node(repo: str, path: Path) -> Node:
    """Read what the plugin in ``path`` ships.

    A repository has at most one plugin. Its skills are the directories of
    ``skills/`` that hold a ``SKILL.md``; with a shelf they are the shelf's
    listed skills, in its order.

    Raises:
        ValueError: If the shelf file lacks a key or names an unknown skill.
    """
    plugins = sorted(p.parent for p in path.glob("plugins/*/.claude-plugin"))
    if not plugins:
        return Node(repo, path, None, ())
    plugin = plugins[0]
    found = sorted(p.parent.name for p in plugin.glob("skills/*/SKILL.md"))
    shelf_file = plugin / "tree" / "shelf.toml"
    if not shelf_file.exists():
        return Node(repo, path, plugin.name, tuple(found))
    raw = tomllib.loads(shelf_file.read_text(encoding="utf-8"))
    try:
        skills = tuple(raw["skills"])
        units = {
            key: Unit(key, u["title"], u["rungs"], u["skill"])
            for key, u in raw["units"].items()
        }
    except (KeyError, TypeError) as exc:
        raise ValueError(f"{shelf_file}: missing key {exc}") from exc
    for unit in units.values():
        if unit.skill not in skills:
            raise ValueError(f"{shelf_file}: unit {unit.key} names no listed skill")
    for skill in skills:
        if skill not in found:
            raise ValueError(f"{shelf_file}: no SKILL.md for {skill}")
    return Node(repo, path, plugin.name, skills, units)


def measured_units(
    pkgs: dict[str, dg.Package], parents: set[str]
) -> dict[tuple[str, str], tuple[str, ...]]:
    """The units of each parent shelf that each dependent repository is carded.

    A repository receives a unit's card when one of its packages does, by
    ``skill_shelf.carded``. Keys are ``(dependent, parent)``; the unit keys
    come in shelf order.
    """
    out: dict[tuple[str, str], tuple[str, ...]] = {}
    for parent in sorted(parents & set(ss.SHELVES)):
        shelf = ss.SHELVES[parent]
        m = ss.measure(shelf, pkgs)
        got: dict[str, set[str]] = {}
        for dist in m.used:
            got.setdefault(pkgs[dist].repo, set()).update(ss.carded(shelf, m, dist))
        for repo, names in got.items():
            out[repo, parent] = tuple(
                slug(u.name) for u in shelf.units if u.name in names
            )
    return out


def build(g: dg.Graph | None = None, paths: dict[str, Path] | None = None) -> Tree:
    """The tree at the submodule pins.

    Args:
        g: The dependency graph; built from the submodules when left out.
        paths: Another checkout to read a repository's plugin from, by
            repository. The graph and the measurements stay at the pins.
    """
    g = g if g is not None else dg.build()
    paths = paths or {}
    nodes = {
        repo: read_node(repo, paths.get(repo, dg.repo_path(repo)))
        for repo in sorted(g.repos)
    }
    shelved = {repo for repo, node in nodes.items() if node.units}
    units = measured_units(g.pkgs, shelved)
    rank = {repo: (dg.LAYER_RANK[layer], repo) for repo, layer in g.repos.items()}
    edges: dict[str, list[Edge]] = {repo: [] for repo in nodes}
    for e in sorted(g.edges, key=lambda e: rank[e.target]):
        edges[e.source].append(
            Edge(e.target, e.kind, units.get((e.source, e.target), ()))
        )
    return Tree(nodes, {repo: tuple(es) for repo, es in edges.items()})


def graph_violations(tree: Tree) -> list[str]:
    """Gate ST-1: no cycle, and every unit an edge names is on the parent's shelf."""
    out: list[str] = []
    sorter = graphlib.TopologicalSorter(
        {repo: [e.parent for e in es] for repo, es in tree.edges.items()}
    )
    try:
        sorter.prepare()
    except graphlib.CycleError as exc:
        out.append(f"ST-1 cycle: {' → '.join(exc.args[1])}")
    for repo, es in tree.edges.items():
        for e in es:
            for unit in e.units:
                if unit not in tree.nodes[e.parent].units:
                    out.append(
                        f"ST-1 {repo} → {e.parent}: skill_shelf.py measures the"
                        f" unit {unit!r}, which {e.parent}'s shelf.toml lacks"
                    )
    return out


def card_file(tree: Tree, repo: str, unit: str | None = None) -> Path | None:
    """Where a repository's card, or one unit's card, is read from."""
    node = tree.nodes[repo]
    if unit is not None:
        own = node.plugin_dir / "tree" / "cards" / f"{unit}.md"
        return own if own.exists() else None
    if node.plugin is not None:
        own = node.plugin_dir / "tree" / "card.md"
        if own.exists():
            return own
    held = CARDS / f"{repo}.md"
    return held if held.exists() else None


def _card(path: Path | None, repo: str) -> str:
    if path is None:
        return f"No card yet: read `AGENTS.md` in {repo}'s repository."
    return path.read_text(encoding="utf-8").strip()


def edge_section(tree: Tree, edge: Edge) -> str:
    """What a block carries for one parent: its heading and its card or cards."""
    parent = tree.nodes[edge.parent]
    declared = EDGE_KINDS[edge.kind]
    if parent.units:
        head = f"{len(edge.units)} of {len(parent.units)} units"
        parts = []
        for key in edge.units:
            unit = parent.units[key]
            parts.append(
                f"#### {unit.title} · {unit.rungs} · skill"
                f" `{parent.plugin}:{unit.skill}`\n\n"
                + _card(card_file(tree, edge.parent, key), edge.parent)
            )
        if not parts:
            parts.append(
                f"It uses fewer than {ss.CARD_THRESHOLD} names of each unit, so no"
                f" card. The front door is `{parent.plugin}:{parent.skills[0]}`."
            )
        body = "\n\n".join(parts)
    else:
        if len(parent.skills) == 1:
            head = f"skill `{parent.plugin}:{parent.skills[0]}`"
        elif parent.skills:
            head = f"{len(parent.skills)} skills"
        else:
            head = "no skill yet"
        body = _card(card_file(tree, edge.parent), edge.parent)
    return f"### {edge.parent} · {declared} · {head}\n\n{body}"


def render_block(tree: Tree, repo: str) -> str:
    """The "Builds on" block of every skill of ``repo``, markers included."""
    lines = [BLOCK_BEGIN, "## Builds on", ""]
    edges = tree.edges[repo]
    if edges:
        lines += [
            "Each card below says what a library under this skill guarantees.",
            "A card is enough to call it.",
            "Load a skill only when its card's last line applies.",
            "",
        ]
        for edge in edges:
            lines += [edge_section(tree, edge), ""]
    else:
        lines += ["Nothing else in the stack: this is a base skill.", ""]
    children = tree.children(repo)
    if children:
        # repository names only: a skill never tells the agent to load a child
        lines += [f"Used by (pointers, not skills to load): {', '.join(children)}.", ""]
    lines.append(BLOCK_END)
    return "\n".join(lines)


def replace_block(text: str, block: str) -> str:
    """``text`` with ``block`` at its end, in place of an earlier block.

    Only the marked region is removed; text an author wrote after an earlier
    block is kept, and the new block goes after it.

    Raises:
        ValueError: If a begin marker has no end marker after it.
    """
    begin = text.find(BLOCK_MARK)
    if begin != -1:
        end = text.find(BLOCK_END, begin)
        if end == -1:
            raise ValueError("skill-tree:begin without skill-tree:end")
        before = text[:begin].rstrip("\n")
        after = text[end + len(BLOCK_END) :].strip("\n")
        text = before + ("\n\n" + after if after else "")
    return text.rstrip("\n") + "\n\n" + block + "\n"


def render(tree: Tree, repo: str) -> dict[Path, str]:
    """Every ``SKILL.md`` of ``repo`` with its block regenerated, by path."""
    node = tree.nodes[repo]
    block = render_block(tree, repo)
    return {
        node.skill_file(skill): replace_block(
            node.skill_file(skill).read_text(encoding="utf-8"), block
        )
        for skill in node.skills
    }


def adopted(tree: Tree, repo: str) -> bool:
    """Whether every skill of ``repo`` carries a generated block."""
    node = tree.nodes[repo]
    return bool(node.skills) and all(
        BLOCK_MARK in node.skill_file(s).read_text(encoding="utf-8")
        for s in node.skills
    )


def _public(module: Path) -> set[str] | None:
    """The names a module file exports: its ``__all__``, else what it binds.

    ``__all__`` is read wherever it is assigned or extended, so names appended
    inside a ``try`` (an optional extra) count. Without one, every name bound
    at the top level counts. ``None`` when the file cannot be parsed.
    """
    try:
        tree = ast.parse(module.read_text(encoding="utf-8"))
    except (OSError, SyntaxError):
        return None
    listed: set[str] = set()
    found = False
    for node in ast.walk(tree):
        targets = (
            node.targets
            if isinstance(node, ast.Assign)
            else [node.target]
            if isinstance(node, ast.AugAssign)
            else []
        )
        if any(isinstance(t, ast.Name) and t.id == "__all__" for t in targets):
            found = True
            listed |= {
                c.value
                for c in ast.walk(node.value)
                if isinstance(c, ast.Constant) and isinstance(c.value, str)
            }
    if found:
        return listed
    bound: set[str] = set()
    for node in tree.body:
        if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef):
            bound.add(node.name)
        elif isinstance(node, ast.Import | ast.ImportFrom):
            bound |= {(a.asname or a.name).split(".")[0] for a in node.names}
        elif isinstance(node, ast.Assign | ast.AnnAssign):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            bound |= {t.id for t in targets if isinstance(t, ast.Name)}
    return bound


def resolves(root: Path, parts: list[str]) -> bool:
    """Whether ``parts`` names a submodule or a public name under ``root``.

    ``root`` is an import package's directory; ``parts`` is what follows the
    package in a dotted name. Leading parts that are submodules are walked
    into; the part after them must be a public name of that module.
    """
    here = root
    for i, part in enumerate(parts):
        # a private submodule counts only when its parent exports it by name
        listed = _public(here / "__init__.py") or set()
        open_ = not part.startswith("_") or part in listed
        if open_ and (here / part).is_dir():
            here = here / part
            continue
        last = i == len(parts) - 1
        if open_ and (here / f"{part}.py").is_file():
            if last:
                return True
            names = _public(here / f"{part}.py")
            return i == len(parts) - 2 and names is not None and parts[-1] in names
        names = _public(here / "__init__.py") if here.is_dir() else None
        return last and names is not None and part in names
    return True


def card_names(tree: Tree, pkgs: dict[str, dg.Package]) -> list[str]:
    """Gate ST-7: every ``package.name`` a card writes in backticks is public.

    A card may name its own library only by a path that exists and is not
    private: each part before the last is a submodule (one with a leading
    underscore only when its parent exports it), and the last is in that
    module's ``__all__``.
    """
    roots: dict[str, dict[str, Path]] = {}
    for pkg in pkgs.values():
        for root in pkg.modules:
            roots.setdefault(pkg.repo, {})[dg._module_name(root)] = root
    out: list[str] = []
    for repo, node in tree.nodes.items():
        files = [card_file(tree, repo)]
        files += [card_file(tree, repo, unit) for unit in node.units]
        modules = roots.get(repo, {})
        for path in files:
            if path is None:
                continue
            text = path.read_text(encoding="utf-8")
            for dotted in sorted(set(re.findall(r"`([A-Za-z_][\w.]*\w)", text))):
                head, *parts = dotted.split(".")
                if head in modules and parts and not resolves(modules[head], parts):
                    out.append(f"ST-7 {repo}: card {path.name} names {dotted}")
    return out


def sources() -> dict[str, str]:
    """Each repository's ``owner/name`` on GitHub, from ``.gitmodules``."""
    parser = configparser.ConfigParser()
    parser.read(ROOT / ".gitmodules", encoding="utf-8")
    out = {}
    for section in parser.sections():
        url = parser[section]["url"].removesuffix(".git")
        out[Path(parser[section]["path"]).name] = "/".join(url.split("/")[-2:])
    return out


def marketplace(tree: Tree, urls: dict[str, str]) -> str:
    """The marketplace: geostack's root plugin, then every repository's plugin.

    Each plugin is fetched from its own repository's default branch, so a
    skill describes the library's latest state, not geostack's pin. An entry
    carries ``dependencies``: the plugins of the repositories it builds on
    directly, and the root plugin when its skills are a shelf (a shelf is
    written in the role ladder). Claude Code installs dependencies with a
    plugin, and theirs in turn.
    """
    root = json.loads(
        (ROOT / "plugins" / ROOT_PLUGIN / ".claude-plugin" / "plugin.json").read_text(
            encoding="utf-8"
        )
    )
    plugins: list[dict] = [
        {
            "name": ROOT_PLUGIN,
            "source": f"./plugins/{ROOT_PLUGIN}",
            "description": root["description"],
        }
    ]
    for repo, node in tree.nodes.items():
        if node.plugin is None or repo in dg.THIRD_PARTY:
            continue
        manifest = json.loads(
            (node.plugin_dir / ".claude-plugin" / "plugin.json").read_text("utf-8")
        )
        entry: dict = {
            "name": manifest["name"],
            "source": {
                "source": "git-subdir",
                "url": urls[repo],
                "path": f"plugins/{node.plugin}",
            },
            "description": manifest["description"],
        }
        parents = [ROOT_PLUGIN] if node.units else []
        parents += [
            str(tree.nodes[e.parent].plugin)
            for e in tree.edges[repo]
            if tree.nodes[e.parent].plugin is not None
        ]
        if parents:
            entry["dependencies"] = parents
        plugins.append(entry)
    data = {
        "name": "geostack",
        "owner": {"name": "jejjohnson"},
        "description": (
            "The GeoStack skill tree: each library's use skills, installed"
            " together with the skills of the libraries it builds on."
        ),
        "plugins": plugins,
    }
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def description_length(text: str) -> int:
    """Length of the ``description`` in a SKILL.md's frontmatter, in characters."""
    if not text.startswith("---"):
        return 0
    lines = text.split("\n---", 1)[0].splitlines()[1:]
    for i, line in enumerate(lines):
        if not line.startswith("description:"):
            continue
        value = line.removeprefix("description:").strip()
        if value in ("", ">", ">-", "|", "|-"):  # a block scalar: indented lines
            block = []
            for cont in lines[i + 1 :]:
                if cont and not cont[0].isspace():
                    break
                block.append(cont.strip())
            value = " ".join(b for b in block if b)
        return len(value)
    return 0


def content_violations(tree: Tree) -> list[str]:
    """Gates ST-2 (current), ST-3 (budgets) and ST-4 (links point down).

    ST-2 holds a repository to its block only once every one of its skills
    carries one; ``pending`` lists the others.
    """
    out: list[str] = []
    ids = {
        f"{node.plugin}:{skill}": repo
        for repo, node in tree.nodes.items()
        for skill in node.skills
    }
    for repo, node in tree.nodes.items():
        if adopted(tree, repo):
            for path, expected in render(tree, repo).items():
                if path.read_text(encoding="utf-8") != expected:
                    out.append(
                        f"ST-2 stale: {repo} {path.relative_to(node.path)}"
                        f" (python scripts/skill_tree.py --write {repo})"
                    )
        allowed = tree.below(repo) | {repo}
        for skill in node.skills:
            text = node.skill_file(skill).read_text(encoding="utf-8")
            label = f"{node.plugin}:{skill}"
            if len(text.splitlines()) >= SKILL_MAX_LINES:
                out.append(f"ST-3 {label}: {len(text.splitlines())} lines")
            if description_length(text) > DESCRIPTION_MAX_CHARS:
                out.append(f"ST-3 {label}: description over {DESCRIPTION_MAX_CHARS}")
            for skill_id, owner in ids.items():
                if owner not in allowed and skill_id in text:
                    out.append(f"ST-4 {label}: names {skill_id}, which is not below it")
        cards = [card_file(tree, repo)]
        for unit in node.units:
            cards.append(card_file(tree, repo, unit))
            if cards[-1] is None:
                out.append(f"ST-3 {repo}: no card for the unit {unit}")
        for path in cards:
            if path is None:
                continue
            n = len(path.read_text(encoding="utf-8").strip().splitlines())
            if n > CARD_MAX_LINES:
                out.append(f"ST-3 {repo}: card {path.name} has {n} lines")
    return out


def violations(tree: Tree, pkgs: dict[str, dg.Package] | None = None) -> list[str]:
    """Every gate checked here: ST-1, then ST-2 to ST-4, and ST-7 given ``pkgs``."""
    found = graph_violations(tree) or content_violations(tree)
    if pkgs is not None and not found:
        found = card_names(tree, pkgs)
    return found


def marketplace_stale(tree: Tree) -> bool:
    """Whether the committed marketplace differs from the generated one."""
    return not MARKETPLACE.exists() or MARKETPLACE.read_text(
        encoding="utf-8"
    ) != marketplace(tree, sources())


def pending(tree: Tree) -> list[str]:
    """Repositories with a skill whose block is not generated yet."""
    return [r for r, n in tree.nodes.items() if n.skills and not adopted(tree, r)]


def summary(tree: Tree) -> str:
    """One row per repository: its skills, its block and what it builds on."""
    rows = ["| Repository | Skills | Block | Builds on |", "|---|---|---|---|"]
    for repo, node in tree.nodes.items():
        skills = ", ".join(f"`{s}`" for s in node.skills) or "none"
        if node.units:
            skills += f" ({len(node.units)} units)"
        state = "generated" if adopted(tree, repo) else "none" if node.skills else ""
        parents = ", ".join(
            f"{e.parent} ({len(e.units)} units)"
            if tree.nodes[e.parent].units
            else e.parent
            for e in tree.edges[repo]
        )
        rows.append(f"| {repo} | {skills} | {state} | {parents} |")
    return "\n".join(rows)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a gate fails")
    parser.add_argument(
        "--write", metavar="REPO", help="write REPO's blocks into its checkout"
    )
    parser.add_argument(
        "--into",
        metavar="PATH",
        type=Path,
        help="with --write: another checkout of REPO, read and written in"
        " place of its submodule",
    )
    args = parser.parse_args(argv)
    if args.into and not args.write:
        parser.error("--into needs --write")
    if args.write in dg.THIRD_PARTY:
        print(f"{args.write} is third party: geostack never writes to it")
        return 1
    paths = {args.write: args.into.resolve()} if args.into else {}
    graph = dg.build()
    tree = build(graph, paths=paths)
    if args.write:
        if args.write not in tree.nodes or not tree.nodes[args.write].skills:
            print(f"{args.write} has no plugin with a skill")
            return 1
        found = graph_violations(tree)
        for message in found:
            print(message)
        if found:
            return 1
        for path, text in render(tree, args.write).items():
            if path.read_text(encoding="utf-8") != text:
                path.write_text(text, encoding="utf-8")
                print(f"wrote {path}")
        return 0
    found = violations(tree, graph.pkgs)
    if args.check and not found and marketplace_stale(tree):
        found = [
            f"stale: {MARKETPLACE.relative_to(ROOT)} (python scripts/skill_tree.py)"
        ]
    for message in found:
        print(message)
    if args.check:
        return 1 if found else 0
    if not found:
        MARKETPLACE.parent.mkdir(exist_ok=True)
        MARKETPLACE.write_text(marketplace(tree, sources()), encoding="utf-8")
    print(summary(tree))
    waiting = pending(tree)
    if waiting:
        print(f"\nno generated block yet: {', '.join(waiting)}")
    return 0


